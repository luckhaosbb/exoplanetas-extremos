// Fallback determinístico caso o backend esteja temporariamente indisponível
export function getDailyExoplanetFallback(date = new Date()) {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date - start;
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const index = dayOfYear % EXOPLANETS.length;
  return EXOPLANETS[index];
}
